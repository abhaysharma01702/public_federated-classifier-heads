def load_runs():
    runs, side = {}, {}
    paths = [(p, "Ada") for p in glob.glob(str(ROOT / "results" / "ada" / "*" / "runs" / "*" / "summary.json"))]
    paths += [(p, "Kaggle") for p in glob.glob(str(ROOT / "results" / "kaggle" / "*" / "*" / "runs" / "*" / "summary.json"))]
    for p, machine in paths:
        parts = Path(p).parts
        module = parts[-4]
        if module in SKIP:
            continue
        s = json.load(open(p))
        exp, setting, method, head, seed = s["run_id"].split("-")[:5]
        rec = dict(s, exp=exp, setting=setting, method=method, head=head, seed=int(seed[1:]), module=module,
                   machine=machine, dir=os.path.dirname(p))
        target = side if module in SIDE else runs
        key = (module, s["run_id"]) if module in SIDE else s["run_id"]
        if key in target:
            raise SystemExit(f"duplicate run {key}")
        target[key] = rec
    return runs, side


def pick(runs, **kw):
    return [r for r in runs.values() if all(r[k] == v for k, v in kw.items())]


def by_seed(rs, field="test_best_mean_f1"):
    return {r["seed"]: r[field] for r in rs}


def msd(vals):
    vals = list(vals)
    if not vals:
        return "n/a"
    return f"{st.mean(vals):.3f} ± {st.stdev(vals):.3f}" if len(vals) > 1 else f"{vals[0]:.3f}"


def boot_ci(diffs, n=10000, seed=0):
    rng = random.Random(seed)
    k = len(diffs)
    means = sorted(st.mean(rng.choice(diffs) for _ in range(k)) for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n) - 1]


def boot_p(diffs, n=10000, seed=0):
    """Two-sided bootstrap p-value for mean difference 0 (centred resampling)."""
    rng = random.Random(seed)
    m = st.mean(diffs)
    centred = [d - m for d in diffs]
    k = len(diffs)
    hits = sum(abs(st.mean(rng.choice(centred) for _ in range(k))) >= abs(m) for _ in range(n))
    return (hits + 1) / (n + 1)


def holm(pvals):
    order = sorted(range(len(pvals)), key=lambda i: pvals[i])
    adj, running = [0.0] * len(pvals), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(pvals) - rank) * pvals[i]))
        adj[i] = running
    return adj


def paired(a: dict, b: dict):
    seeds = sorted(set(a) & set(b))
    return seeds, [a[s] - b[s] for s in seeds]


def write_csv(name, header, rows):
    TAB.mkdir(parents=True, exist_ok=True)
    with open(TAB / name, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def val_curve(run_dir):
    """Mean validation macro-F1 over the four languages, per evaluated round."""
    p = Path(run_dir) / "metrics_round.csv"
    if not p.exists():
        return {}
    acc = defaultdict(list)
    for r in csv.DictReader(open(p)):
        if r["split"] == "validation":
            acc[int(r["round"])].append(float(r["macro_f1"]))
    return {k: st.mean(v) for k, v in sorted(acc.items()) if len(v) == 4}


